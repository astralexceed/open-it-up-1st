#!/usr/bin/env python3
"""Bakes the text of the setup screens into src/core/ui_font_data.h.

Usage: make_ui_font.py Inter-Medium.otf Inter-SemiBold.otf > src/core/ui_font_data.h
Needs Pillow. Run it again if a title uses a letter that the large face does not have.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

BODY_EM = 28
DISPLAY_EM = 64
ATLAS_WIDTH = 1024
PADDING = 2
ACCENTS = "ÁÉÍÓÚÑáéíóúñ¿¡"
BODY_CHARS = "".join(chr(c) for c in range(32, 127)) + ACCENTS
DISPLAY_CHARS = "".join(sorted(set("Map controls Mapear controles Calibrate audio Calibrar audio 0123456789+-/ ms")))


def bake(path, em, chars, sheet, cursor):
    font = ImageFont.truetype(path, em, layout_engine=ImageFont.Layout.BASIC)
    glyphs = []
    x, y, row = cursor
    for ch in chars:
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w, h = max(0, right - left), max(0, bottom - top)
        if x + w + PADDING * 2 > ATLAS_WIDTH:
            x, y, row = 0, y + row, 0
        cell_x, cell_y = x + PADDING, y + PADDING
        if w and h:
            ImageDraw.Draw(sheet).text((cell_x - left, cell_y - top), ch, font=font, fill=255, anchor="ls")
        glyphs.append((ord(ch), cell_x, cell_y, w, h, left, top, round(font.getlength(ch) * 256)))
        x += w + PADDING * 2
        row = max(row, h + PADDING * 2)
    return glyphs, (0, y + row, 0)


def pack(sheet, height):
    pixels = sheet.crop((0, 0, ATLAS_WIDTH, height)).tobytes()
    out = []
    i = 0
    while i < len(pixels):
        value = pixels[i] >> 4
        run = 1
        while run < 16 and i + run < len(pixels) and pixels[i + run] >> 4 == value:
            run += 1
        out.append((run - 1) << 4 | value)
        i += run
    return out


def table(name, glyphs):
    rows = ",\n".join("    {%d, %d, %d, %d, %d, %d, %d, %d}" % g for g in glyphs)
    return "inline constexpr UiGlyph %s[] = {\n%s,\n};\n" % (name, rows)


def main():
    sheet = Image.new("L", (ATLAS_WIDTH, 2048), 0)
    body, cursor = bake(sys.argv[1], BODY_EM, BODY_CHARS, sheet, (0, 0, 0))
    display, cursor = bake(sys.argv[2], DISPLAY_EM, DISPLAY_CHARS, sheet, cursor)
    height = cursor[1]
    data = pack(sheet, height)
    print("// Generated by tools/make_ui_font.py from the Inter typeface (SIL OFL 1.1, see assets/fonts). Do not edit.")
    print("\n#pragma once\n\n#include <cstdint>\n\nnamespace piu {\n")
    print("struct UiGlyph {\n  std::uint16_t code, x, y;\n  std::int16_t w, h, left, top;\n  std::int32_t advance;\n};\n")
    print("inline constexpr int kUiFontWidth = %d;\ninline constexpr int kUiFontHeight = %d;" % (ATLAS_WIDTH, height))
    print("inline constexpr int kUiBodyEm = %d;\ninline constexpr int kUiDisplayEm = %d;\n" % (BODY_EM, DISPLAY_EM))
    print(table("kUiBodyGlyphs", body))
    print(table("kUiDisplayGlyphs", display))
    print("// One byte per run: (length - 1) << 4 | coverage in sixteenths.")
    print("inline constexpr std::uint8_t kUiFontRuns[] = {")
    for i in range(0, len(data), 28):
        print("    " + ",".join(str(v) for v in data[i : i + 28]) + ",")
    print("};\n\n}  // namespace piu")


if __name__ == "__main__":
    main()
